 function correctTypos(question){
  const words=knownWords();
  return normalizeText(question).split(' ').map(word=>{
   if(word.length<4||words.includes(word)||stopWords.has(word))return word;
   const limit=word.length>=7?2:1;let best=word,bestDistance=limit+1;
   for(const known of words){const distance=editDistance(word,known);if(distance<bestDistance){best=known;bestDistance=distance}}
   return best;
  }).join(' ');
 }
